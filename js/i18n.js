// Current language (default: zh)
window.CURRENT_LANG = 'zh';

// Get translation helper
window.t = function(key) {
  return (window.I18N[window.CURRENT_LANG] && window.I18N[window.CURRENT_LANG][key]) || key;
};

// Switch language
window.switchLang = function(lang) {
  window.CURRENT_LANG = lang;
  localStorage.setItem('mindtest_lang', lang);
  location.reload();
};

// Init language from localStorage
(function() {
  const saved = localStorage.getItem('mindtest_lang');
  if (saved && window.I18N[saved]) {
    window.CURRENT_LANG = saved;
  }
})();
